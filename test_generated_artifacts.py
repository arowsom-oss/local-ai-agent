def tool_results(result):
    return [m["content"] for m in result.messages if isinstance(m, dict) and m.get("role") == "tool"]


def test_both_generation_tools_register_immutable_media_after_own_approval():
    with tempfile.TemporaryDirectory() as folder, patch.object(artifacts, "store", artifacts.Store()), \
            patch.object(generation_tools, "OUTPUT_DIR", Path(folder)):
        for kind, suffix in (("image", ".png"), ("video", ".mp4")):
            body = ("fixed synthetic " + kind).encode()
            path = Path(folder) / (("a" if kind == "image" else "b") * 32 + suffix)
            path.write_bytes(body)
            with patch.object(h.core, "run_generation", return_value={"path": str(path)}) as generate:
                result = h.run_calls([h.tool_call("generate_" + kind, {"prompt": "A sailboat"})])
            assert [p[0] for p in result.popups] == ["generation"]
            assert "Artifacts" in result.popups[0][1]["output"]
            generate.assert_called_once_with(kind, "A sailboat", None)
            item = artifacts.store.items()[-1]
            assert item.kind == kind and item.current.data == body
            assert f"Artifact {item.number}" in tool_results(result)[0]
            assert "Downloads" not in tool_results(result)[0]
            path.write_bytes(b"later file change")
            assert item.current.data == body


def test_registration_failure_is_an_error_with_recovery_and_does_not_retry():
    with tempfile.TemporaryDirectory() as folder, patch.object(artifacts, "store", artifacts.Store()), \
            patch.object(generation_tools, "OUTPUT_DIR", Path(folder)):
        for _ in range(artifacts.MAX_ARTIFACTS):
            artifacts.store.create("Existing", "document", "Keep")
        path = Path(folder) / ("c" * 32 + ".png")
        path.write_bytes(b"generated bytes")
        with patch.object(h.core, "run_generation", return_value={"path": str(path)}) as generate:
            result = h.run_calls([h.tool_call("generate_image", {"prompt": "A sailboat"}),
                                  h.tool_call("generate_video", {"prompt": "Do not retry with another tool"})])
        text = tool_results(result)[0]
        assert text.startswith("Error:") and "Open generated image or video" in text
        assert "Do not regenerate automatically" in text
        assert generate.call_count == 1 and path.read_bytes() == b"generated bytes"
        assert len(result.popups) == 1 and "paused for this turn" in tool_results(result)[1]
        assert any(line.startswith("[blocked]") for line in result.logs)
        assert len(artifacts.store.items()) == artifacts.MAX_ARTIFACTS


def test_malformed_or_untrusted_worker_output_cannot_add_an_artifact():
    with patch.object(artifacts, "store", artifacts.Store()):
        for response in (None, [], {}, {"path": None}, {"path": 12},
                         {"path": str(Path(r"C:\Users\Someone\Downloads") / ("a" * 32 + ".png"))},
                         {"error": "synthetic generation failure"}):
            with patch.object(h.core, "run_generation", return_value=response):
                result = h.run_calls([h.tool_call("generate_image", {"prompt": "A sailboat"})])
            assert tool_results(result)[0].startswith("Error:")
            assert not artifacts.store.items()


def test_stop_after_generation_does_not_add_or_claim_delivery():
    with patch.object(artifacts, "store", artifacts.Store()):
        halted = []
        def generate(*args):
            halted.append(True)
            return {"path": "fixed output"}
        with patch.object(h.core, "run_generation", side_effect=generate), \
                patch.object(h.core, "stopped", side_effect=lambda event: bool(halted)):
            result = h.run_calls([h.tool_call("generate_image", {"prompt":"A sailboat"})],
                                 expected_answer="(stopped by you)")
        assert not artifacts.store.items()
        assert "completed after Stop" in tool_results(result)[0]


def panel_fixture(store, dirty=False):
    notes, loaded, revealed = [], [], []
    panel = types.SimpleNamespace(selected=store.get(1), dirty=dirty, signature=((1, 1),),
        status=types.SimpleNamespace(set=notes.append),
        choice=types.SimpleNamespace(configure=lambda **kw: None),
        on_change=lambda: revealed.append(True))
    def load(number):
        loaded.append(number)
        panel.selected = store.get(number)
    panel.load = load
    return panel, notes, loaded, revealed


def test_new_image_and_video_select_themselves_over_an_older_artifact():
    store = artifacts.Store()
    store.create("Article", "document", "Keep this article")
    panel, notes, loaded, revealed = panel_fixture(store)
    with patch.object(artifact_panel, "store", store):
        for kind in ("image", "video"):
            item = store.media("Generated " + kind, kind, b"synthetic bytes")
            artifact_panel.ArtifactPanel.refresh(panel)
            assert panel.selected.number == item.number
            assert loaded[-1] == item.number and revealed
        before = len(loaded)
        artifact_panel.ArtifactPanel.refresh(panel)
        assert len(loaded) == before  # Do not restart a preview on every timer tick.


def test_new_media_preserves_dirty_text_and_still_announces_where_to_find_it():
    store = artifacts.Store()
    original = store.create("Article", "document", "Saved article")
    panel, notes, loaded, revealed = panel_fixture(store, dirty=True)
    with patch.object(artifact_panel, "store", store):
        image = store.media("Generated image", "image", b"synthetic bytes")
        artifact_panel.ArtifactPanel.refresh(panel)
    assert not loaded and panel.selected == original and panel.dirty
    assert revealed and f"Artifact {image.number}" in notes[-1]
    assert "unsaved text is preserved" in notes[-1]


def test_reopen_generated_uses_original_bytes_without_regeneration_or_download():
    with tempfile.TemporaryDirectory() as folder, patch.object(artifacts, "store", artifacts.Store()), \
            patch.object(generation_tools, "OUTPUT_DIR", Path(folder)):
        path = Path(folder) / ("d" * 32 + ".mp4")
        path.write_bytes(b"previous generated video")
        notes, loaded = [], []
        panel = types.SimpleNamespace(stop_event=threading.Event(), discard_ok=lambda: True,
            status=types.SimpleNamespace(set=notes.append), selected=None, refresh=lambda: None,
            load=loaded.append)
        with patch.object(artifact_panel.filedialog, "askopenfilename", return_value=str(path)) as picker, \
                patch.object(generation_tools, "run_generation", side_effect=AssertionError("No generation")):
            artifact_panel.ArtifactPanel.open_generated(panel)
        item = artifacts.store.items()[0]
        assert item.kind == "video" and item.current.data == b"previous generated video"
        assert loaded == [item.number]
        assert picker.call_args.kwargs["initialdir"] == str(Path(folder))
        artifacts.store.clear()
        assert path.exists()  # New chat/restart recovery uses the retained file.


def test_reopen_generated_refuses_other_folders_and_stop_or_cancel():
    with tempfile.TemporaryDirectory() as folder, patch.object(artifacts, "store", artifacts.Store()), \
            patch.object(generation_tools, "OUTPUT_DIR", Path(folder) / "generated"):
        generated = Path(folder) / "generated"
        generated.mkdir()
        outsider = Path(folder) / ("e" * 32 + ".png")
        outsider.write_bytes(b"outside generated")
        notes = []
        panel = types.SimpleNamespace(stop_event=threading.Event(), discard_ok=lambda: True,
            status=types.SimpleNamespace(set=notes.append), selected=None,
            refresh=lambda: (_ for _ in ()).throw(AssertionError("must refuse")),
            load=lambda n: (_ for _ in ()).throw(AssertionError("must refuse")))
        with patch.object(artifact_panel.filedialog, "askopenfilename", return_value=str(outsider)):
            artifact_panel.ArtifactPanel.open_generated(panel)
        assert "Open refused" in notes[-1] and not artifacts.store.items()
        with patch.object(artifact_panel.filedialog, "askopenfilename", return_value=""):
            artifact_panel.ArtifactPanel.open_generated(panel)
        panel.stop_event.set()
        with patch.object(artifact_panel.filedialog, "askopenfilename", side_effect=AssertionError("Stopped")):
            artifact_panel.ArtifactPanel.open_generated(panel)
        panel.stop_event.clear()
        def picker(**kwargs):
            panel.stop_event.set()
            return str(outsider)
        with patch.object(artifact_panel.filedialog, "askopenfilename", side_effect=picker):
            artifact_panel.ArtifactPanel.open_generated(panel)
        assert not artifacts.store.items()


